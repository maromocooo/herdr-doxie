ORDER = ["run1", "run2", "run3", "sit", "house", "lie", "lie1", "lie0", "house_empty"]


def grid(name):
    rows = [r for r in SPRITES[name].strip("\n").split("\n")]
    assert len(rows) == 16, (name, len(rows))
    for r in rows:
        assert len(r) == 16, (name, r, len(r))
    return [[c == "#" for c in r] for r in rows]
